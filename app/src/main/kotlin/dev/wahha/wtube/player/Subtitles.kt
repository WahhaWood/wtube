package dev.wahha.wtube.player

import android.net.Uri
import android.util.Log
import androidx.annotation.OptIn
import androidx.media3.common.util.UnstableApi
import androidx.media3.datasource.ByteArrayDataSource
import androidx.media3.datasource.DataSource
import androidx.media3.datasource.DataSpec
import androidx.media3.datasource.TransferListener
import dev.wahha.wtube.data.Http
import okhttp3.Request
import org.schabi.newpipe.extractor.stream.SubtitlesStream

/** One caption track offered in the player; [translated] ones are YouTube's machine translation of another track. */
class SubtitleTrack(val url: String, val language: String, val auto: Boolean, val translated: Boolean = false)

/** [content] of an extractor subtitle stream as WebVTT, optionally translated by YouTube into [translateTo]. */
fun subtitleUrl(content: String, translateTo: String? = null): String =
    content.replace(Regex("&(fmt|tlang)=[^&]*"), "") + "&fmt=vtt" + translateTo?.let { "&tlang=$it" }.orEmpty()

/**
 * The video's caption tracks, plus a machine translation into [translateTo] when the video has no track
 * in that language. The translation starts from a human track in the spoken language (the language of the
 * auto-generated track), else the auto-generated one, else any human track: that is what translates best.
 */
fun subtitleTracks(streams: List<SubtitlesStream>, translateTo: String): List<SubtitleTrack> {
    val unique = streams.distinctBy { it.languageTag to it.isAutoGenerated }
    val tracks = unique.map { SubtitleTrack(subtitleUrl(it.content), it.languageTag, it.isAutoGenerated) }
    if (unique.isEmpty() || unique.any { it.languageTag.sameLanguage(translateTo) }) return tracks
    val spoken = unique.firstOrNull { it.isAutoGenerated }?.languageTag
    val source = unique.firstOrNull { !it.isAutoGenerated && spoken != null && it.languageTag.sameLanguage(spoken) }
        ?: unique.firstOrNull { it.isAutoGenerated }
        ?: unique.first()
    return tracks + SubtitleTrack(subtitleUrl(source.content, translateTo), translateTo, auto = true, translated = true)
}

/** "pt-BR" and "pt" are one language for picking tracks. */
fun String.sameLanguage(other: String) = substringBefore('-').equals(other.substringBefore('-'), ignoreCase = true)

private const val EMPTY_VTT = "WEBVTT\n"

/** Tries per caption file, with a growing pause: a machine translation often answers 429 once and then goes through. */
private const val FETCH_ATTEMPTS = 3

/**
 * The whole caption file, or an empty WebVTT when YouTube refuses it. Its own machine translation
 * (`tlang`) answers 429 without a PO token, so a translated track is the original one translated
 * on the device ([translateOnDevice]); finished translations are kept for the next time the track is picked.
 */
fun fetchSubtitles(url: String): String {
    val target = Regex("[?&]tlang=([^&]*)").find(url)?.groupValues?.get(1) ?: return fetchTrack(url)
    translations[url]?.let { return it }
    val source = Regex("[?&]lang=([^&]*)").find(url)?.groupValues?.get(1) ?: return EMPTY_VTT
    val original = fetchTrack(url.replace(Regex("&tlang=[^&]*"), ""))
    if (original == EMPTY_VTT) return EMPTY_VTT
    return runCatching { translateOnDevice(original, source, target) }
        .onSuccess { translations[url] = it }
        .getOrElse {
            Log.w("WTubeSubtitles", "Translating the caption track failed", it)
            EMPTY_VTT
        }
}

private val translations = object : LinkedHashMap<String, String>(4, 0.75f, true) {
    override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, String>) = size > 3
}

private fun fetchTrack(url: String): String {
    repeat(FETCH_ATTEMPTS) { attempt ->
        if (attempt > 0) Thread.sleep(1_000L * attempt)
        val vtt = runCatching {
            val request = Request.Builder().url(url).header("User-Agent", Http.USER_AGENT).build()
            Http.client.newCall(request).execute().use { response ->
                val body = response.body.string().trimStart('\uFEFF')
                if (response.isSuccessful && body.startsWith("WEBVTT")) body else {
                    Log.w("WTubeSubtitles", "Caption track refused (try ${attempt + 1}): HTTP ${response.code}, ${body.length} chars: ${body.take(60).replace('\n', ' ')}")
                    null
                }
            }
        }.getOrElse {
            Log.w("WTubeSubtitles", "Caption track failed (try ${attempt + 1})", it)
            null
        }
        if (vtt != null) return vtt
    }
    return EMPTY_VTT
}

/**
 * Serves caption files through [fetchSubtitles], so a refused track plays as an empty one: a failed load
 * of a merged text source would otherwise stop the whole video with a source error.
 */
@OptIn(UnstableApi::class)
class SubtitleDataSource : DataSource {
    private var delegate: ByteArrayDataSource? = null
    private var uri: Uri? = null

    override fun open(dataSpec: DataSpec): Long {
        uri = dataSpec.uri
        val source = ByteArrayDataSource(fetchSubtitles(dataSpec.uri.toString()).toByteArray())
        delegate = source
        return source.open(dataSpec)
    }

    override fun read(buffer: ByteArray, offset: Int, length: Int): Int = checkNotNull(delegate).read(buffer, offset, length)

    override fun getUri(): Uri? = uri

    override fun close() {
        delegate?.close()
        delegate = null
    }

    override fun addTransferListener(transferListener: TransferListener) = Unit
}
