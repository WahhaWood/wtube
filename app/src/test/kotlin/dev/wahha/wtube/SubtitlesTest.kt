package dev.wahha.wtube

import dev.wahha.wtube.player.subtitleTracks
import dev.wahha.wtube.player.subtitleUrl
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.SubtitlesStream

class SubtitlesTest {
    private fun stream(language: String, auto: Boolean) = SubtitlesStream.Builder()
        .setContent("https://www.youtube.com/api/timedtext?v=x&lang=$language${if (auto) "&kind=asr" else ""}&fmt=ttml", true)
        .setMediaFormat(MediaFormat.TTML)
        .setLanguageCode(language)
        .setAutoGenerated(auto)
        .build()

    @Test
    fun urlAsksForWebVttAndTranslation() {
        val base = "https://www.youtube.com/api/timedtext?v=x&lang=en&fmt=srv3&tlang=de"
        assertEquals("https://www.youtube.com/api/timedtext?v=x&lang=en&fmt=vtt", subtitleUrl(base))
        assertEquals("https://www.youtube.com/api/timedtext?v=x&lang=en&fmt=vtt&tlang=ru", subtitleUrl(base, translateTo = "ru"))
    }

    @Test
    fun translationStartsFromHumanTrackInSpokenLanguage() {
        val tracks = subtitleTracks(listOf(stream("de", false), stream("en", true), stream("en", false)), translateTo = "ru")
        assertEquals(4, tracks.size)
        val translated = tracks.last()
        assertTrue(translated.translated)
        assertEquals("ru", translated.language)
        assertTrue("from the human English track", "lang=en&fmt=vtt&tlang=ru" in translated.url && "asr" !in translated.url)
    }

    @Test
    fun noTranslationWhenTheLanguageIsThere() {
        val tracks = subtitleTracks(listOf(stream("en", false), stream("ru-RU", true)), translateTo = "ru")
        assertTrue(tracks.none { it.translated })
        assertTrue(subtitleTracks(emptyList(), translateTo = "ru").isEmpty())
    }
}
