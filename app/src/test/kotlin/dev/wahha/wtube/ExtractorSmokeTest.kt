        println("channel: popular ${popular.size}, search ${found.size}, about videos ${about?.videos}, joined ${about?.joined}")
        assertTrue(popular.isNotEmpty() && found.isNotEmpty() && about != null && about.videos > 0)
    }

    // 24/7 radio streams are live around the clock; search marks them only by the missing length.
    @Test
    fun searchMarksStreamsLiveNow() = runBlocking {
        val live = YouTube.search("lofi hip hop radio").items.filterIsInstance<VideoItem>().filter { it.isLive }
        println("search live: ${live.size}, e.g. ${live.firstOrNull()?.title}")
        assertTrue(live.isNotEmpty())
        val vods = YouTube.search("Rick Astley Never Gonna Give You Up").items.filterIsInstance<VideoItem>().filter { it.duration > 0 }
        assertTrue(vods.isNotEmpty() && vods.none { it.isLive })
    }

    @Test
    fun recommendationsFromHistorySkipWatched() = runBlocking {
        val watched = "jNQXAC9IVRw"
        // Recommendations swallow a failed seed; asking for it directly surfaces a bot check (skipped on CI).
        YouTube.video(watched)
        val page = YouTube.recommendations(listOf(watched), setOf(watched))
        val videos = page.items.filterIsInstance<VideoItem>()
        println("recommendations: ${videos.size} videos")
        assertTrue(videos.isNotEmpty())
        assertTrue(videos.none { it.id == watched })
    }

    @Test
    fun liveStreamHasHls() = runBlocking {
        val live = YouTube.kiosk("live").items.filterIsInstance<VideoItem>().first { it.isLive }
        val info = YouTube.streamInfo(live.id)
        println("live: ${live.id} ${info.streamType} hls=${info.hlsUrl.take(60)}")
        assertTrue(info.streamType.isLive())
        assertTrue(info.hlsUrl.isNotEmpty())
    }

    @Test
    fun liveChatAndReplayLoadAnonymously() = runBlocking {
        val live = YouTube.kiosk("live").items.filterIsInstance<VideoItem>().first { it.isLive }
        val chat = Actions.watch(live.id, session = null).chat
        println("live chat of ${live.id}: $chat")
        assertTrue(chat != null && !chat.replay)
        val page = LiveChat.page(chat!!.token, replay = false)
        assertTrue(page.continuation != null && page.modes.size == 2)
        // Lofi Girl's past streams keep their chat replay.
        val channel = YouTube.channel("https://www.youtube.com/@LofiGirl")
        val past = YouTube.channelTab(channel.tabs.first { it.kind == "livestreams" }).items.filterIsInstance<VideoItem>().first { !it.isLive && it.duration > 0 }
        val replay = Actions.watch(past.id, session = null).chat
        println("chat replay of ${past.id}: $replay")
        assertTrue(replay != null && replay.replay)
        val messages = LiveChat.page(replay!!.token, replay = true, offsetMs = 600_000).actions.filterIsInstance<ChatAction.Add>()
        println("replay messages near 10:00: ${messages.size}")
        assertTrue(messages.isNotEmpty() && messages.all { it.message.offsetMs >= 0 })
    }

    @Test
    fun channelHasVideosTabWithoutShorts() = runBlocking {
        val channel = YouTube.channel("https://www.youtube.com/@YouTube")
        println("channel ${channel.name}: tabs ${channel.tabs.map { it.kind }}")
        assertTrue(channel.tabs.none { it.kind == "shorts" })
        val videos = YouTube.channelTab(channel.tabs.first())
        assertTrue(videos.items.isNotEmpty())
    }
}
