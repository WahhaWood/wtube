/**
 * Live checks against YouTube through the real extractor and HTTP stack: when these fail, YouTube changed
 * something and the extractor needs a bump (see Plan.md, "Поддержка"). Needs network.
 */
class ExtractorSmokeTest {
    companion object {
        @JvmStatic
        @BeforeClass
        fun init() = YouTube.init("RU")
    }

    // On CI (GitHub's data-centre IPs) YouTube asks to sign in before giving streams: that says nothing
    // about the extractor, so such a test counts as skipped there. Anywhere else it is a failure.
    @get:Rule
    val botCheck = TestRule { base, _ ->
        object : Statement() {
            override fun evaluate() {
                try {
                    base.evaluate()
                } catch (e: Throwable) {
                    val botCheck = generateSequence(e) { it.cause }.any { it is SignInConfirmNotBotException }
                    if (botCheck && System.getenv("CI") != null) throw AssumptionViolatedException("YouTube bot check on CI", e)
                    throw e
                }
            }
        }
    }

    @Test
    fun streamInfoHasDashableVideoAndAudio() = runBlocking {
        val info = YouTube.streamInfo("jNQXAC9IVRw")
        val selection = selectStreams(info.videoOnlyStreams, info.audioStreams, VideoCodec.entries)
        println("video: " + selection.video.joinToString { "${it.itag} ${it.codec} ${it.height}p ${it.deliveryMethod}" })
        println("audio: " + selection.audio.flatten().joinToString { "${it.itag} ${it.codec} ${it.averageBitrate}k" })
        assertTrue("no video-only streams", selection.video.isNotEmpty())
        assertTrue("no audio streams", selection.audio.isNotEmpty())
    }

    /** The bytes really come: the same POST + range parameter request the player's data source sends. */
    @Test
    fun streamUrlServesRangeRequests() = runBlocking {
        val info = YouTube.streamInfo("jNQXAC9IVRw")
        val audio = selectStreams(info.videoOnlyStreams, info.audioStreams, VideoCodec.entries).audio.first().first()
        val url = audio.content + "&range=0-1023&rn=0"
        val ua = if (YoutubeParsingHelper.isVisionOsStreamingUrl(url)) YoutubeParsingHelper.getVisionOsUserAgent(null) else Http.USER_AGENT
        val request = Request.Builder().url(url).header("User-Agent", ua).post(byteArrayOf(0x78, 0).toRequestBody()).build()
        Http.client.newCall(request).execute().use { response ->
            assertEquals(200, response.code)
            assertEquals(1024, response.body.bytes().size)
        }
    }

    /**
     * Caption tracks download as WebVTT. YouTube's machine translation (`tlang`) is only reported: Google
     * rate-limits it per IP with a 429 "Sorry" page, and then the player shows an empty track instead.
     */
    @Test
    fun subtitlesDownload() = runBlocking {
        val info = YouTube.streamInfo("jNQXAC9IVRw")
        println("subtitles: " + info.subtitles.joinToString { "${it.languageTag}${if (it.isAutoGenerated) "(auto)" else ""}" })
        val track = info.subtitles.first()
        val original = fetchSubtitles(subtitleUrl(track.content))
        assertTrue("not WebVTT: ${original.take(100)}", "-->" in original)
        val translated = fetchSubtitles(subtitleUrl(track.content, translateTo = "ru"))
        println("translation: " + if ("-->" in translated) "works" else "refused")
    }

    // The transcript comes from a caption track as json3: get_transcript wants a PO token.
    @Test
    fun transcriptFromCaptionTracks() = runBlocking {
        val captions = YouTube.video("dQw4w9WgXcQ").captions
        println("caption tracks: " + captions.joinToString { it.language + if (it.auto) "(auto)" else "" })
        for (track in listOfNotNull(Transcript.preferred(captions, "ru"), captions.firstOrNull { it.auto })) {
            val lines = Transcript.load(track)
            println("${track.language}${if (track.auto) "(auto)" else ""}: ${lines.size} lines, first \"${lines.firstOrNull()?.text}\"")
            assertTrue(lines.size > 10)
            assertEquals(lines.map { it.startMs }.sorted(), lines.map { it.startMs })
        }
    }

    @Test
    fun anonymousWatchHasMostReplayed() = runBlocking {
        val heatmap = Actions.watch("dQw4w9WgXcQ", session = null).heatmap
        println("heatmap: ${heatmap.size} slices, peak at ${heatmap.indexOf(heatmap.maxOrNull())}")
        assertTrue(heatmap.size >= 50 && heatmap.all { it in 0f..1f })
    }

    @Test
    fun searchHasNoShorts() = runBlocking {
        val page = YouTube.search("minecraft")
        val videos = page.items.filterIsInstance<VideoItem>()
        println("search: ${page.items.size} items, ${videos.size} videos")
        assertTrue(videos.isNotEmpty())
        assertTrue(page.next != null)
    }

    // Signed out, comments come through InnerTube too: that is where sorting and replies are.
    @Test
    fun anonymousCommentsSortAndReplies() = runBlocking {
        val token = Actions.watch("dQw4w9WgXcQ", session = null).commentsToken
        assertTrue(token != null)
        val top = Actions.comments(token, null, session = null)
        println("comments: ${top.comments.size}, sorts ${top.sortTokens.size}, next ${top.continuation != null}")
        assertTrue(top.comments.isNotEmpty() && top.sortTokens.size == 2 && top.continuation != null)
        val newest = Actions.comments(top.sortTokens[1], null, session = null)
        assertTrue(newest.comments.isNotEmpty() && newest.comments.first().id != top.comments.first().id)
        val thread = top.comments.first { it.repliesPage != null }
        val replies = Actions.comments(null, thread.repliesPage, session = null)
        println("replies of ${thread.id}: ${replies.comments.size}")
        assertTrue(replies.comments.isNotEmpty())
    }

    // Signed requests must reach YouTube's sign-in check: an hl it rejects ("en-RU") made every one a 400.
    @Test
    fun signedRequestIsJudgedBySession() = runBlocking {
        val fake = Session(cookie = "SAPISID=AbCdEfGhIjKlMnOp/QrStUvWxYz012345; __Secure-3PAPISID=AbCdEfGhIjKlMnOp/QrStUvWxYz012345; SID=x")
        val result = runCatching { InnerTube.browse(fake, browseId = Feeds.HOME) }
        println("signed request with fake cookies: ${result.exceptionOrNull()}")
        assertTrue(result.exceptionOrNull() is SessionExpiredException)
    }

    // Downloads: H.264 qualities and AAC sound of known size, fetched by range the way the service does.
    @Test
    fun downloadOptionsAndRangeFetch() = runBlocking {
        val info = YouTube.streamInfo("jNQXAC9IVRw")
        val options = downloadOptions(info)
        println("download options: $options")
        assertTrue(options.any { !it.audioOnly && it.height >= 240 } && options.last().audioOnly && options.all { it.bytes > 0 })
        val audio = info.audioStreams.first { it.format == org.schabi.newpipe.extractor.MediaFormat.M4A && it.itagItem?.contentLength ?: -1 > 0 }
        val length = audio.itagItem!!.contentLength
        val bytes = Http.client.newCall(YoutubeRequests.rangeRequest(audio.content, 0, minOf(length, 100_000))).execute().use { it.body.bytes() }
        assertEquals(minOf(length, 100_000), bytes.size.toLong())
        // An MP4 starts with its "ftyp" box.
        assertEquals("ftyp", String(bytes, 4, 4))
    }

    @Test
    fun channelSortsSearchAndAbout() = runBlocking {
        val channel = "UCSJ4gkVC6NrvII8umztf0Ow"
        val extras = Channels.extras(channel)
        assertEquals(3, extras.videoSorts.size)
        val popular = Channels.sortedVideos(extras.videoSorts[1]).items.filterIsInstance<VideoItem>()
        val found = Channels.search(channel, "study").items.filterIsInstance<VideoItem>()
